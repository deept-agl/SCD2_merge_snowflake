-- Execute with a role permitted to create warehouses and databases.
CREATE WAREHOUSE IF NOT EXISTS WH_CUSTOMER_ETL
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS CUSTOMER_ANALYTICS_DB;
CREATE SCHEMA IF NOT EXISTS CUSTOMER_ANALYTICS_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS CUSTOMER_ANALYTICS_DB.GOLD;

USE WAREHOUSE WH_CUSTOMER_ETL;
USE DATABASE CUSTOMER_ANALYTICS_DB;

-- Each source row is a full customer snapshot received from an upstream system.
-- In production, an ingestion service would populate this table.
CREATE OR REPLACE TABLE BRONZE.CUSTOMERS (
    SOURCE_RECORD_ID NUMBER IDENTITY START 1 INCREMENT 1,
    CUSTOMER_ID NUMBER NOT NULL,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(100),
    MEMBERSHIP_TIER VARCHAR(30),
    SOURCE_UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- A customer has one current version and may have several expired versions.
-- VALID_TO is exclusive; NULL identifies the current version.
CREATE OR REPLACE TABLE GOLD.DIM_CUSTOMER (
    CUSTOMER_ID NUMBER NOT NULL,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(100),
    MEMBERSHIP_TIER VARCHAR(30),
    VALID_FROM TIMESTAMP_NTZ NOT NULL,
    VALID_TO TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN NOT NULL
);

-- An append-only stream tracks new snapshots inserted into the source table.
CREATE OR REPLACE STREAM BRONZE.CUSTOMERS_STREAM
  ON TABLE BRONZE.CUSTOMERS
  APPEND_ONLY = TRUE;
