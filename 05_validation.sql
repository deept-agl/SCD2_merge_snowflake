USE DATABASE CUSTOMER_ANALYTICS_DB;

-- Show versions in the order they became effective in the warehouse.
SELECT CUSTOMER_ID, CUSTOMER_NAME, CITY, MEMBERSHIP_TIER,
       VALID_FROM, VALID_TO, IS_CURRENT
FROM GOLD.DIM_CUSTOMER
ORDER BY CUSTOMER_ID, VALID_FROM;

-- Every customer should have exactly one current version.
SELECT CUSTOMER_ID, COUNT(*) AS CURRENT_VERSIONS
FROM GOLD.DIM_CUSTOMER
WHERE IS_CURRENT = TRUE
GROUP BY CUSTOMER_ID;


-- Check overlaps between versions of the same customer.
SELECT a.CUSTOMER_ID, a.VALID_FROM AS FIRST_START, b.VALID_FROM AS SECOND_START
FROM GOLD.DIM_CUSTOMER a
JOIN GOLD.DIM_CUSTOMER b
  ON a.CUSTOMER_ID = b.CUSTOMER_ID
 AND a.VALID_FROM < b.VALID_FROM
 AND (a.VALID_TO IS NULL OR a.VALID_TO > b.VALID_FROM);

-- Show recent task executions and any errors in this project.
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME => 'TASK_LOAD_DIM_CUSTOMER', RESULT_LIMIT => 20
))
ORDER BY SCHEDULED_TIME DESC;

-- Check whether any new source rows remain unprocessed.
SELECT SYSTEM$STREAM_HAS_DATA('CUSTOMER_ANALYTICS_DB.BRONZE.CUSTOMERS_STREAM')
  AS HAS_UNPROCESSED_SOURCE_ROWS;
